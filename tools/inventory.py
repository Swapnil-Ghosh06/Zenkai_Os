"""Lists every file under G:/Aeon with its size, last-change date and any version number found inside it, and
reads the version of the bundled fonts. Writes docs/INVENTORY.md. Run: python tools/inventory.py
Dates: files tracked by git use the date of the last commit that touched them; everything else uses the file's
modified time. Read-only: it never changes the files it lists."""
import os
import re
import struct
import subprocess
import sys
from datetime import datetime

ROOT = "G:/Aeon"
REPO = "G:/Aeon/OS"
SKIP_DIRS = {".git", "target", "__pycache__", ".claude"}
TEXT_EXT = {".md", ".rs", ".toml", ".py", ".sh", ".ps1", ".yml", ".yaml", ".txt", ".csv", ".json", ".lock", ".html", ".cfg", ".gitignore", ".gitattributes"}
VERSION_RE = re.compile(r"\b(?:Aeon |version |v)?(\d+\.\d+\.\d+)\b")


def git_dates():
    out = subprocess.run(["git", "-C", REPO, "log", "--format=@%cs", "--name-only"], capture_output=True, text=True).stdout
    dates, cur = {}, None
    for line in out.splitlines():
        if line.startswith("@"):
            cur = line[1:]
        elif line.strip() and cur and line not in dates:
            dates[line] = cur
    return dates


def font_version(path):
    """The 'name' table entry 5 (version string) of a TrueType font, or '?'."""
    try:
        d = open(path, "rb").read()
        n = struct.unpack(">H", d[4:6])[0]
        for i in range(n):
            tag, _, off, ln = struct.unpack(">4sIII", d[12 + 16 * i:28 + 16 * i])
            if tag == b"name":
                base = off
                count, str_off = struct.unpack(">HH", d[base + 2:base + 6])
                for j in range(count):
                    pid, eid, lid, nid, ln2, o2 = struct.unpack(">HHHHHH", d[base + 6 + 12 * j:base + 18 + 12 * j])
                    if nid == 5:
                        raw = d[base + str_off + o2:base + str_off + o2 + ln2]
                        return raw.decode("utf-16-be" if pid in (0, 3) else "latin-1", errors="replace")
    except Exception as e:  # noqa: BLE001
        return f"? ({e})"
    return "?"


def main():
    gd = git_dates()
    rows = []
    for dirpath, dirs, files in os.walk(ROOT):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for f in files:
            p = os.path.join(dirpath, f).replace("\\", "/")
            rel = os.path.relpath(p, ROOT).replace("\\", "/")
            size = os.path.getsize(p)
            if rel.startswith("OS/") and rel[3:] in gd:
                date, src = gd[rel[3:]], "git"
            else:
                date, src = datetime.fromtimestamp(os.path.getmtime(p)).strftime("%Y-%m-%d"), "file"
            ver = ""
            ext = os.path.splitext(f)[1].lower()
            if ext == ".ttf":
                ver = font_version(p)
            elif ext in TEXT_EXT and size < 400_000:
                try:
                    text = open(p, encoding="utf-8", errors="ignore").read()
                    found = sorted(set(VERSION_RE.findall(text)))
                    ver = ", ".join(found[:4])
                except OSError:
                    pass
            rows.append((rel, size, date, src, ver))
    rows.sort()
    out = ["# File inventory", "", f"Generated by `tools/inventory.py` on {datetime.now():%Y-%m-%d}. {len(rows)} files under `G:/Aeon` (not counting `.git`, `target`, `.claude`).",
           "Date = last git commit that touched the file (`git`) or the file's modified time (`file`). Versions = version-like numbers found inside the file (first four).", "",
           "| File | Bytes | Last change | Date from | Versions inside |", "|---|---:|---|---|---|"]
    for rel, size, date, src, ver in rows:
        out.append(f"| `{rel}` | {size} | {date} | {src} | {ver} |")
    open(os.path.join(REPO, "docs", "INVENTORY.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    by = {}
    for rel, size, date, src, ver in rows:
        top = rel.split("/")[0]
        by.setdefault(top, []).append((date, size))
    for k, v in sorted(by.items()):
        print(f"{k}: {len(v)} files, {sum(s for _, s in v)} bytes, oldest {min(d for d, _ in v)}, newest {max(d for d, _ in v)}")
    for f in ("tools/fonts/Inter.ttf", "tools/fonts/JetBrainsMono.ttf"):
        print(f, "->", font_version(os.path.join(REPO, f)))


if __name__ == "__main__":
    sys.exit(main())
