#!/usr/bin/env python3
"""Rasterises the Aeon fonts into src/fontdata.rs (8-bit coverage per glyph).

Run from the repo root:  python tools/genfont.py
Needs Pillow (build time only; the generated file is committed, nothing is needed to build Aeon).
Fonts: Inter (sans) and JetBrains Mono (shell), both SIL Open Font License 1.1, see docs/licenses/.
"""
import hashlib
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "tools", "fonts")
OUT = os.path.join(ROOT, "src", "fontdata.rs")
ASCII = list(range(0x20, 0x7F))

# name, file, pixel size, variation settings by axis name, characters
FACES = [
    ("SANS_16", "Inter.ttf", 16, {"opsz": 16, "wght": 450}, ASCII),
    ("SANS_24", "Inter.ttf", 24, {"opsz": 24, "wght": 500}, ASCII),
    ("WORDMARK", "Inter.ttf", 88, {"opsz": 32, "wght": 800}, [ord(c) for c in "AEON"]),
    ("MONO", "JetBrainsMono.ttf", 15, {"wght": 450}, ASCII),
    ("MONO_L", "JetBrainsMono.ttf", 22, {"wght": 450}, ASCII),
]


def load(file, size, axes):
    f = ImageFont.truetype(os.path.join(FONTS, file), size)
    names = [a["name"].decode() if isinstance(a["name"], bytes) else a["name"] for a in f.get_variation_axes()]
    vals = []
    for a, n in zip(f.get_variation_axes(), names):
        key = {"Optical Size": "opsz", "Optical size": "opsz", "Weight": "wght"}.get(n, n)
        vals.append(max(a["minimum"], min(a["maximum"], axes.get(key, a["default"]))))
    f.set_variation_by_axes(vals)
    return f


def raster(f, ch, pad=4):
    asc, desc = f.getmetrics()
    w = int(f.getlength(ch)) + 2 * pad + f.size
    h = asc + desc + 2 * pad
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((pad, pad + asc), ch, font=f, fill=255, anchor="ls")
    bbox = img.getbbox()
    adv = max(0, round(f.getlength(ch)))
    if bbox is None:
        return adv, 0, 0, 0, 0, b""
    x0, y0, x1, y1 = bbox
    crop = img.crop(bbox)
    return adv, x1 - x0, y1 - y0, x0 - pad, (pad + asc) - y0, bytes(crop.tobytes())


def main():
    out = [
        "//! GENERATED by tools/genfont.py. Do not edit by hand.\n",
        "//! Glyph coverage for Inter and JetBrains Mono (SIL Open Font License 1.1, see docs/licenses/).\n",
        "\n",
        "/// One glyph: `advance` pixels to the next glyph, a `w` x `h` coverage bitmap starting at `off` in the\n",
        "/// face's coverage table, drawn `left` pixels right of the pen and `top` pixels above the baseline.\n",
        "#[derive(Clone, Copy, Debug)]\n",
        "pub struct GlyphData {\n    pub advance: u8,\n    pub w: u8,\n    pub h: u8,\n    pub left: i8,\n    pub top: i8,\n    pub off: u32,\n}\n\n",
    ]
    total = 0
    for name, file, size, axes, chars in FACES:
        chars = sorted(set(chars))  # the kernel looks glyphs up with a binary search
        f = load(file, size, axes)
        asc, desc = f.getmetrics()
        glyphs, cov = [], bytearray()
        for c in chars:
            adv, w, h, left, top, data = raster(f, chr(c))
            assert adv < 256 and w < 256 and h < 256 and -128 <= left < 128 and -128 <= top < 128, (name, chr(c))
            glyphs.append((adv, w, h, left, top, len(cov)))
            cov += data
        total += len(cov)
        out.append(f"pub const {name}_ASCENT: u8 = {asc};\n")
        out.append(f"pub const {name}_HEIGHT: u8 = {asc + desc};\n")
        out.append(f"pub const {name}_SIZE: u8 = {size};\n")
        out.append(f"pub static {name}_CODES: [u8; {len(chars)}] = {list(chars)};\n".replace("[", "[", 1))
        out.append(f"pub static {name}_GLYPHS: [GlyphData; {len(chars)}] = [\n")
        for g in glyphs:
            out.append(f"    GlyphData {{ advance: {g[0]}, w: {g[1]}, h: {g[2]}, left: {g[3]}, top: {g[4]}, off: {g[5]} }},\n")
        out.append("];\n")
        out.append(f"pub static {name}_COV: [u8; {len(cov)}] = [\n")
        for i in range(0, len(cov), 32):
            out.append("    " + ", ".join(str(b) for b in cov[i:i + 32]) + ",\n")
        out.append("];\n\n")
        if name.startswith("MONO"):
            out.append(f"pub const {name}_CELL_W: u8 = {round(f.getlength('M'))};\n")
            out.append(f"pub const {name}_CELL_H: u8 = {asc + desc};\n\n")
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("".join(out))
    print(f"wrote {OUT}: {total} coverage bytes, source sha256 {hashlib.sha256(open(os.path.join(FONTS,'Inter.ttf'),'rb').read()).hexdigest()[:12]}")
    if total > 80 * 1024:
        sys.exit(f"font data is {total} bytes, over the 80 KiB budget")


if __name__ == "__main__":
    main()
